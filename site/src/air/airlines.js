const N = S.length / 5;
/** "ACA810" → "AC810"; anything else comes back unchanged */
export function iataCall(c) {
  if (!/^[A-Z]{3}\d/.test(c || "")) return c || "";
  let lo = 0, hi = N - 1;
  const k = c.slice(0, 3);
  while (lo <= hi) {
    const mid = (lo + hi) >> 1, r = S.slice(mid * 5, mid * 5 + 3);
    if (r === k) return S.slice(mid * 5 + 3, mid * 5 + 5) + c.slice(3);
    if (r < k) lo = mid + 1; else hi = mid - 1;
  }
  return c;
}
