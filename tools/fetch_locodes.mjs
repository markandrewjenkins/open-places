// Port names for Sea Traffic ship destinations (src/ships/destination.js): the UN/LOCODE entries that matter here,
// written as a compact module, site/src/ships/locodes.js. UN/LOCODE is published by UNECE free of charge; this reads the
// machine-readable copy kept by the Frictionless "datasets/un-locode" project (ODC-PDDL). Kept: every port (function 1)
// in British Columbia, Washington, Oregon, California, Alaska and Hawaii, plus the major Pacific ports whose codes ships
// in the Salish Sea broadcast as their destination (MAJOR below), with coordinates where UN/LOCODE has them (LOCODE_LL).
// Run by hand when the list should change:
//   node tools/fetch_locodes.mjs
// Polite: one request, a descriptive User-Agent.
import { writeFileSync } from "node:fs";

const SRC = "https://raw.githubusercontent.com/datasets/un-locode/main/data/code-list.csv";
const OUT = new URL("../site/src/ships/locodes.js", import.meta.url);
const REGIONS = { CA: ["BC"], US: ["WA", "OR", "CA", "AK", "HI"] };
const MAJOR = `CNSHA CNNGB CNSZX CNYTN CNSHK CNTAO CNTXG CNDLC CNXMN CNCAN CNNSA CNLYG CNRZH CNFOC HKHKG TWKHH TWTPE TWTXG KRPUS KRINC KRKAN KRUSN KRPTK
  JPTYO JPYOK JPNGO JPUKB JPOSA JPCHB JPHKT JPKIJ JPSMZ JPMIZ JPTMK JPHSM JPKWS JPSKD JPTOY SGSIN MYPKG MYTPP VNSGN VNVUT VNCMT VNHPH THLCH THBKK PHMNL PHSFS IDJKT IDTPP IDSUB
  AUSYD AUMEL AUBNE AUNTL AUPHE AUDAM NZAKL NZTRG NZLYT RUVVO RUVYP RUNJK RUPKC MXZLO MXLZC MXESE MXMZT PABLB PAMIT CLSAI CLVAP PECLL ECGYE COBUN INNSA LKCMB AEJEA`.split(/\s+/).filter(Boolean);
const COUNTRY = { CA: "Canada", US: "USA", CN: "China", HK: "Hong Kong", TW: "Taiwan", KR: "South Korea", JP: "Japan", SG: "Singapore", MY: "Malaysia", VN: "Vietnam", TH: "Thailand",
  PH: "Philippines", ID: "Indonesia", AU: "Australia", NZ: "New Zealand", RU: "Russia", MX: "Mexico", PA: "Panama", CL: "Chile", PE: "Peru", EC: "Ecuador", CO: "Colombia", IN: "India", LK: "Sri Lanka", AE: "UAE" };

/** one CSV line → fields (quoted fields may hold commas) */
function fields(line) {
  const out = []; let cur = "", q = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (q) { if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c; }
    else if (c === '"') q = true; else if (c === ",") { out.push(cur); cur = ""; } else cur += c;
  }
  out.push(cur);
  return out;
}
const r = await fetch(SRC, { headers: { "User-Agent": "openplaces-locode/1.0 (static file build)" } });
if (!r.ok) throw new Error(`UN/LOCODE: HTTP ${r.status}`);
const lines = (await r.text()).split(/\r?\n/);
const head = fields(lines[0]), ix = Object.fromEntries(head.map((h, i) => [h, i]));
const want = new Set(MAJOR), ports = {}, ll = {};
// "4826N 12321W" → [lon, lat] (degrees and minutes), or null when the entry has no coordinates
const coord = (c) => { const m = /^(\d{2})(\d{2})([NS]) (\d{3})(\d{2})([EW])$/.exec(String(c || "").trim()); if (!m) return null;
  const lat = (+m[1] + +m[2] / 60) * (m[3] === "S" ? -1 : 1), lon = (+m[4] + +m[5] / 60) * (m[6] === "W" ? -1 : 1); return [+lon.toFixed(2), +lat.toFixed(2)]; };
for (const line of lines.slice(1)) {
  if (!line) continue;
  const f = fields(line), cc = f[ix.Country], loc = f[ix.Location], sub = f[ix.Subdivision], fn = f[ix.Function] || "", code = cc + loc;
  if (f[ix.Change] === "X") continue;   // marked for deletion
  const regional = REGIONS[cc]?.includes(sub) && fn[0] === "1";
  if (!regional && !want.has(code)) continue;
  const where = cc === "CA" || cc === "US" ? sub : COUNTRY[cc] || cc;
  // several Chinese port codes ships still broadcast (CNSHA, CNNGB, CNTAO, …) now name the city's airport: keep the city
  const name = f[ix.Name].replace(/\s+\S+\s+International Apt$/, "").replace(/\s+International Apt$/, "");
  ports[code] = `${name}, ${where}`;
  const c = coord(f[ix.Coordinates]); if (c) ll[code] = c;
}
const missing = MAJOR.filter((c) => !ports[c]);
if (missing.length) console.log(`not in UN/LOCODE: ${missing.join(" ")}`);
const body = `// Generated by tools/fetch_locodes.mjs from UN/LOCODE (UNECE, free of charge; via the datasets/un-locode copy, ODC-PDDL).
// UN/LOCODE "CCLLL" → "Port name, province/state or country": every port in BC, WA, OR, CA, AK and HI, and the major Pacific
// ports Salish Sea shipping sails to. Don't edit by hand; change the script and run it again.
export const LOCODE_CREDIT = "Port names: UN/LOCODE (UNECE)";
export const LOCODES = ${JSON.stringify(ports).replace(/","/g, '",\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, ",\n}")};
// where each port is, [lon, lat] to 0.01° (the ship card's dashed "probable route"), where UN/LOCODE gives coordinates
export const LOCODE_LL = ${JSON.stringify(ll)};
`;
writeFileSync(OUT, body);
console.log(`${Object.keys(ports).length} ports → ${OUT.pathname}`);
